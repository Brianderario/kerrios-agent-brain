#!/usr/bin/env node
// Regenerates data/companies.json as a READ-ONLY CACHE of the KMG Console CRM
// (the system of record since 2026-06-11). The inbox sweep uses this snapshot
// only as an offline fallback when the Console API is unreachable; all writes
// go to the Console via the V1 API.
//
// Usage: node scripts/console-crm-snapshot.mjs

import { readFileSync, writeFileSync } from 'node:fs';
import { homedir } from 'node:os';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const OUT = join(ROOT, 'data/companies.json');
const RAILS_BASE = process.env.KERRIHQ_API_BASE || 'https://kerrihq-rails-xtua.onrender.com/api/v1';

function loadEnv(path) {
  const out = {};
  for (const line of readFileSync(path, 'utf8').split('\n')) {
    const m = line.match(/^([A-Z0-9_]+)=(.*)$/);
    if (m) out[m[1]] = m[2].replace(/^["']|["']$/g, '');
  }
  return out;
}
const TOKEN = loadEnv(join(homedir(), '.kerri-chief/secrets/kerrihq.env')).KERRIHQ_AGENT_API_KEY;
if (!TOKEN) { console.error('KERRIHQ_AGENT_API_KEY missing'); process.exit(1); }

const sleep = ms => new Promise(r => setTimeout(r, ms));
let lastCall = 0;
async function fetchAll(path) {
  const all = [];
  for (let page = 1; ; page++) {
    const wait = lastCall + 750 - Date.now();
    if (wait > 0) await sleep(wait);
    lastCall = Date.now();
    const res = await fetch(`${RAILS_BASE}${path}?page=${page}&per_page=100`, {
      headers: { Authorization: `Bearer ${TOKEN}` },
    });
    if (!res.ok) throw new Error(`GET ${path} -> ${res.status}: ${(await res.text()).slice(0, 200)}`);
    const { data, meta } = await res.json();
    all.push(...data);
    if (!meta.has_more) return all;
  }
}

const companies = await fetchAll('/companies');
const withDomain = companies.filter(c => c.domain);
const out = {
  description: 'READ-ONLY snapshot of the KMG Console CRM (kerrihq-rails), the system of record since 2026-06-11. Regenerated by scripts/console-crm-snapshot.mjs. Used by the inbox sweep ONLY as an offline fallback for customer lookup — never write here; write to the Console API.',
  schema: 'domain -> { name, jobId, prefix, slug, aliases, primaryContact?, note, consoleId, firstSeenAt, lastTouchedAt }',
  updatedAt: new Date().toISOString(),
  companies: Object.fromEntries(withDomain.map(c => [c.domain, {
    name: c.name,
    jobId: c.job_id || null,
    prefix: c.job_id ? c.job_id[0] : null,
    slug: c.slug || null,
    aliases: c.aliases || [],
    note: (c.crm_notes || '').slice(0, 500),
    consoleId: c.id,
    firstSeenAt: c.first_seen_at || null,
    lastTouchedAt: c.last_touched_at || null,
  }])),
};
writeFileSync(OUT, JSON.stringify(out, null, 2) + '\n');
const skipped = companies.length - withDomain.length;
console.log(`Snapshot written: ${withDomain.length} companies (${skipped} without a domain omitted) -> ${OUT}`);
